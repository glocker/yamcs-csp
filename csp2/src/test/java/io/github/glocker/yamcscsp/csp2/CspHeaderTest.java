package io.github.glocker.yamcscsp.csp2;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.yamcs.utils.StringConverter.hexStringToArray;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.CsvFileSource;
import org.junit.jupiter.params.provider.ValueSource;

public class CspHeaderTest {

    @Test
    public void testKnownHeader() {
        // CRC vector header from libcsp reference vectors, written out by hand
        var bytes = new byte[] { 0x40, 0x05, 0x00, 0x0C, (byte) 0xA5, 0x01 };

        assertHeader(CspHeader.parse(bytes), 1, 5, 3, 10, 20, 1);
    }

    @Test
    public void testBytesAfterHeaderAreIgnored() {
        // Complete frame of CRC vector: header, payload 01 02 03 and CRC32 trailer
        var frame = hexStringToArray("4005000CA501010203F130F21E");

        assertHeader(CspHeader.parse(frame), 1, 5, 3, 10, 20, 1);
    }

    @ParameterizedTest
    @ValueSource(ints = { 0, 1, 5 })
    public void testShortArrayIsRejected(int length) {
        assertThrows(IllegalArgumentException.class, () -> CspHeader.parse(new byte[length]));
    }

    /**
     * Runs once for every line of reference vector files generated by libcsp. The first eight columns are the
     * input given to libcsp, so they are expected values; frame_hex is what libcsp produced
     */
    @ParameterizedTest(name = "{0} [{1}]")
    @CsvFileSource(resources = { "/vectors/vectors-data.csv", "/vectors/vectors-header_data.csv" })
    public void testVectors(String name, String crcMode, int priority, int destination, int source,
            int destinationPort, int sourcePort, int flags, String payloadHex, String frameHex, String expected) {
        var frame = hexStringToArray(frameHex);

        if (frame.length < CspHeader.SIZE) {
            // Vector "truncated_5_bytes": a frame cut below header size
            assertThrows(IllegalArgumentException.class, () -> CspHeader.parse(frame));
            return;
        }
        assertHeader(CspHeader.parse(frame), priority, destination, source, destinationPort, sourcePort, flags);
    }

    private static void assertHeader(CspHeader header, int priority, int destination, int source,
            int destinationPort, int sourcePort, int flags) {
        assertEquals(priority, header.getPriority(), "priority");
        assertEquals(destination, header.getDestination(), "destination");
        assertEquals(source, header.getSource(), "source");
        assertEquals(destinationPort, header.getDestinationPort(), "destination port");
        assertEquals(sourcePort, header.getSourcePort(), "source port");
        assertEquals(flags, header.getFlags(), "flags");
    }
}
